"""Drive the real Nigrani MCP server over stdio (temp DB + copied registry) and record docs/mcp_demo.md."""
from __future__ import annotations

import asyncio
import json
import os
import shutil
import sys
import tempfile
from pathlib import Path

from mcp import ClientSession, StdioServerParameters
from mcp.client.stdio import stdio_client

ROOT = Path(__file__).resolve().parent.parent


async def main() -> None:
    tmp = Path(tempfile.mkdtemp()); shutil.copytree(ROOT / "artifacts" / "registry", tmp / "registry")
    env = {**os.environ, "NIGRANI_DB": f"sqlite:///{tmp / 'demo.db'}", "NIGRANI_REGISTRY": str(tmp / "registry"), "NIGRANI_MCP_ACTOR": "copilot"}
    out = ["# Real MCP session against `nigrani.mcp_server` (stdio)\n\nGenerated by `python docs/mcp_demo.py` (temp DB, copied registry).\n"]
    p = StdioServerParameters(command=sys.executable, args=["-m", "nigrani.mcp_server"], env=env, cwd=str(ROOT))
    async with stdio_client(p) as (r, w), ClientSession(r, w) as s:
        await s.initialize()
        tools = (await s.list_tools()).tools
        out.append(f"## tools/list ({len(tools)})\n" + "\n".join(f"- `{t.name}` — {(t.description or '').splitlines()[0]}" for t in tools))
        res = (await s.list_resources()).resources; tpl = (await s.list_resource_templates()).resource_templates
        pr = (await s.list_prompts()).prompts
        out.append("## resources / templates / prompts\n" + "\n".join([f"- resource `{x.uri}`" for x in res] + [f"- template `{x.uri_template}`" for x in tpl] + [f"- prompt `{x.name}`" for x in pr]))

        async def call(n: str, a: dict | None = None) -> dict:
            r_ = await s.call_tool(n, a or {}); txt = r_.content[0].text
            out.append(f"## tools/call `{n}` {json.dumps(a or {})}\n```json\n{txt[:1200]}{' …' if len(txt) > 1200 else ''}\n```")
            try:
                return json.loads(txt)
            except json.JSONDecodeError:
                return {"text": txt}

        await call("sync_alerts")
        q = await call("list_alerts", {"pattern": "pump", "page_size": 3}); a = q["items"][0]; aid, acct = a["alert_id"], a["account"]
        await call("explain_alert", {"alert_id": aid})
        await call("get_counterparty_network", {"account": acct, "date": aid[:10]})
        await call("assign_alert", {"alert_id": aid, "assignee": "ria"})
        await call("escalate_alert", {"alert_id": aid, "reason": "same-side co-trading cluster in illiquid symbol"})
        c = await call("create_case", {"title": f"Pump ring around {acct}", "alert_ids": [aid]})
        await call("add_case_note", {"case_id": c["case_id"], "body": "Pulled 5-day trades; 4 KYC-linked accounts."})
        await call("draft_case_note", {"alert_id": aid})
        await call("queue_stats"); await call("drift_report", {"recent_days": 20})
        bad = await s.call_tool("close_alert", {"alert_id": "1999-01-01:1", "disposition": "true_positive"})
        out.append(f"## error path: close unknown alert\nis_error={bad.is_error}\n```\n{bad.content[0].text[:300]}\n```")
        pm = await s.get_prompt("triage_alert", {"alert_id": aid})
        out.append(f"## prompts/get `triage_alert`\n```\n{pm.messages[0].content.text[:800]}\n```")
    (ROOT / "docs" / "mcp_demo.md").write_text("\n\n".join(out) + "\n"); shutil.rmtree(tmp)
    print("\n\n".join(out)[:2500])


asyncio.run(main())
